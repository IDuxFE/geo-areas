import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)

/** Generate only the seven-continent presentation, excluding CLDR's political groupings. */
export function generateContinents() {
  const containment = require('cldr-core/supplemental/territoryContainment.json').supplemental
    .territoryContainment
  const names = {
    'zh-CN': require('cldr-localenames-full/main/zh/territories.json').main.zh.localeDisplayNames
      .territories,
    en: require('cldr-localenames-full/main/en/territories.json').main.en.localeDisplayNames
      .territories,
  }
  function territories(id) {
    const children = containment[id]?._contains
    return children ? children.flatMap(territories) : [id]
  }
  const data = ['142', '150', '003', '005', '002', '009', '010'].map((code) => ({
    code,
    name: Object.fromEntries(
      Object.entries(names).map(([locale, labels]) => [
        locale,
        labels[code === '010' ? 'AQ' : code],
      ]),
    ),
    // CLDR places AQ in QO (Outlying Oceania); seven-continent grouping gives it its own group.
    regions: code === '010' ? ['AQ'] : territories(code).filter((region) => region !== 'AQ'),
  }))
  const seen = new Set()
  for (const continent of data) {
    if (Object.values(continent.name).some((name) => !name))
      throw new Error('Missing continent name')
    for (const region of continent.regions) {
      if (!/^[A-Z]{2}$/.test(region) || seen.has(region)) {
        throw new Error(`Invalid or duplicate continent region: ${region}`)
      }
      seen.add(region)
    }
  }
  return `// Generated by scripts/update.mjs. Do not edit.\nexport const continentData = ${JSON.stringify(data)}\n`
}
